# Writes the menu's logo_data.h: the logo and its small copy (run tables),
# their light palette, the "aRVern" wordmark and the subtitle line (2-bit
# coverage bitmaps), taken from the logo demo's generated tables
# (../demo_arvern_logo/logo_data.h, made by its tools/logo2c.py).
#
#   tools/logo_subset.py ../demo_arvern_logo/logo_data.h logo_data.h
#----------------------------------------------------------------------------
import re
import sys

DEFINES = ('LOGO_PAL_NR', 'LOGO_TRACE_BASE', 'LOGO_TRACE_NR', 'LOGO_W', 'LOGO_H', 'LOGO_LAYERS', 'LOGO_RUNS',
           'SPRITE_W', 'SPRITE_H', 'SPRITE_LAYERS', 'SPRITE_RUNS',
           'WORDMARK_W', 'WORDMARK_H', 'WORDMARK_STRIDE', 'TXT_SUB_W', 'TXT_SUB_H', 'TXT_SUB_STRIDE')
TABLES = ('logo_pal_light', 'logo_layer_idx', 'logo_layer_start', 'logo_runs',
          'sprite_layer_idx', 'sprite_layer_start', 'sprite_runs', 'wordmark_bits', 'txt_sub_bits')


def main():
    src = open(sys.argv[1]).read()
    out = ['/* Generated by tools/logo_subset.py from ../demo_arvern_logo/logo_data.h: do not edit. */',
           '#ifndef LOGO_DATA_H', '#define LOGO_DATA_H', '', '#include <stdint.h>', '']
    for d in DEFINES:
        m = re.search(r'^#define\s+%s\s.*$' % d, src, re.M)
        if not m:
            sys.exit('logo_subset.py: no %s in %s' % (d, sys.argv[1]))
        out.append(m.group(0))
    out.append('')
    for t in TABLES:
        m = re.search(r'^static const [^\n]*\b%s\[\d+\] = \{.*?\};' % t, src, re.M | re.S)
        if not m:
            sys.exit('logo_subset.py: no %s in %s' % (t, sys.argv[1]))
        out += [m.group(0), '']
    out.append('#endif /* LOGO_DATA_H */')
    open(sys.argv[2], 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
