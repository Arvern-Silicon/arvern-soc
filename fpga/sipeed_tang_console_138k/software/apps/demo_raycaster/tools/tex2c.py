# Builds the stored wall texture of the raycaster demo, the poster wall
# (128 x 128): bricks with a dark plate carrying the aRVern logo (rendered from
# the logo SVG like demo_arvern_logo, its 24 circuit traces merged into one
# colour). Texels are indices into one palette, stored column by column (the
# renderer draws columns). The other walls are generated by the firmware at
# start-up; the palette also holds the colours they use, named by TEX_C_*
# constants, and stays within TEX_COLOURS entries (the firmware adds its own
# colours after them).
#
#   tools/tex2c.py <light.svg> <dark.svg> <out.h> [--preview PNG]
#----------------------------------------------------------------------------
import argparse
import os
import random
import sys
import tempfile

from PIL import Image

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', '..', 'demo_arvern_logo', 'tools'))
import logo2c                                                   # noqa: E402

TEX_COLOURS = 26

# Colours the firmware's generated walls use, by name (TEX_C_<name>)
NAMED = [('MORTAR', (92, 86, 80))] + \
        [('BRICK%d' % i, c) for i, c in enumerate([(150, 62, 40), (132, 54, 36), (166, 76, 48),
                                                   (118, 50, 34), (142, 70, 46), (158, 58, 38)])] + \
        [('PLATE', (28, 30, 36)), ('STEEL', (70, 72, 80)), ('LIGHT', (0xca, 0xb5, 0xa2)),
         ('TAN', (0xa1, 0x8b, 0x74)), ('GOLD', (0xcb, 0x94, 0x52)), ('TRACE', (0x42, 0x86, 0xbd)),
         ('WHITE', (255, 255, 255))]
MORTAR = (92, 86, 80)
BRICKS = [(150, 62, 40), (132, 54, 36), (166, 76, 48), (118, 50, 34), (142, 70, 46), (158, 58, 38)]
PLATE = (28, 30, 36)
PLATE_EDGE = (70, 72, 80)


def bricks(seed, T, k=1):
    """Bricks 16k x 8k with k-pixel mortar lines on a T x T texture."""
    rnd = random.Random(seed)
    img = [[MORTAR] * T for _ in range(T)]
    bw, bh = 16 * k, 8 * k
    for row in range(T // bh):
        off = bw // 2 if row & 1 else 0
        for b in range(-1, T // bw + 1):
            c = rnd.choice(BRICKS)
            for y in range(row * bh + k, row * bh + bh):
                for x in range(b * bw + off + k, b * bw + off + bw):
                    if 0 <= x < T:
                        img[y][x] = c
    return img


def poster(light, dark, T=128):
    img = bricks(2, T, T // 64)
    # dark plate with a light edge, two pixels wide
    x0, y0, x1, y1 = 6, 20, T - 6, T - 20
    for y in range(y0, y1):
        for x in range(x0, x1):
            edge = x - x0 < 2 or x1 - 1 - x < 2 or y - y0 < 2 or y1 - 1 - y < 2
            img[y][x] = PLATE_EDGE if edge else PLATE
    # the logo, without antialiasing, traces in one colour
    pal = {'index': {}, 'order': []}
    with tempfile.TemporaryDirectory() as tmp:
        rows = logo2c.build(light, dark, x1 - x0 - 4, pal, tmp)
    h = len(rows)
    oy = y0 + ((y1 - y0) - h) // 2
    for y, row in enumerate(rows):
        for x, k in enumerate(row):
            if k == 0:
                continue
            rgb = logo2c.hex_rgb(logo2c.TRACE_COLOUR) if k[0] == 'trace' else logo2c.hex_rgb(k[1])
            img[oy + y][x0 + 2 + x] = rgb
    return img


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('light')
    ap.add_argument('dark')
    ap.add_argument('out_h')
    ap.add_argument('--preview')
    args = ap.parse_args()

    texs = [poster(open(args.light).read(), open(args.dark).read())]
    colours = [c for _, c in NAMED]
    for t in texs:
        for row in t:
            for c in row:
                if c not in colours:
                    colours.append(c)
    assert len(colours) <= TEX_COLOURS, '%d colours' % len(colours)

    out = ['/* Generated by tools/tex2c.py from the aRVern logo SVGs: do not edit. */',
           '#ifndef TEX_DATA_H', '#define TEX_DATA_H', '', '#include <stdint.h>', '',
           '#define TEX_NR          %du' % len(texs),
           '#define TEX_COLOURS     %du   /* palette entries used */' % len(colours)] + \
          ['#define TEX_C_%-9s %du' % (n, colours.index(c)) for n, c in NAMED] + ['',
           '#ifdef TEX_DATA_TABLES',
           'static const uint32_t tex_pal[%d] = {' % len(colours)]
    ws = ['0x%02x%02x%02xu' % c for c in colours]
    for k in range(0, len(ws), 8):
        out.append('    ' + ', '.join(ws[k:k + 8]) + ',')
    out.append('};')
    out.append('/* Texture t: 1 << tex_log2[t] texels square, texel (x, y) at')
    out.append(' * tex_texels[t][(x << tex_log2[t]) + y] (column by column) */')
    for i, t in enumerate(texs):
        T = len(t)
        out.append('static const uint8_t  tex%d[%d] = {' % (i, T * T))
        vals = [colours.index(t[y][x]) for x in range(T) for y in range(T)]
        for k in range(0, len(vals), 32):
            out.append('    ' + ','.join(str(v) for v in vals[k:k + 32]) + ',')
        out.append('};')
    out.append('static const uint8_t *const tex_texels[%d] = { %s };'
               % (len(texs), ', '.join('tex%d' % i for i in range(len(texs)))))
    out.append('static const uint8_t  tex_log2[%d] = { %s };'
               % (len(texs), ', '.join(str(len(t).bit_length() - 1) for t in texs)))
    out += ['#endif /* TEX_DATA_TABLES */', '', '#endif /* TEX_DATA_H */', '']
    open(args.out_h, 'w').write('\n'.join(out))

    if args.preview:
        W = sum(len(t) + 4 for t in texs)
        img = Image.new('RGB', (W, max(len(t) for t in texs)), (255, 255, 255))
        ox = 0
        for t in texs:
            for y in range(len(t)):
                for x in range(len(t)):
                    img.putpixel((ox + x, y), t[y][x])
            ox += len(t) + 4
        img.resize((img.width * 3, img.height * 3), Image.NEAREST).save(args.preview)
    print('%d textures, %d colours' % (len(texs), len(colours)))


if __name__ == '__main__':
    main()
