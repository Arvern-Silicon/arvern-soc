# Renders the scroller font of the effects demo: IBM Plex Sans Bold (SIL Open
# Font License), the characters of CHARS only, antialiased to 2-bit coverage
# (0 none .. 3 full ink) and stored column by column, since the scroller draws
# one screen column at a time. Each glyph column is FONT_H levels, four per
# byte (top pixel in bits [1:0]), in FONT_COL_BYTES bytes.
#
#   tools/font2c.py <out.h> [--size PX] [--preview PNG]
#----------------------------------------------------------------------------
import argparse
import os

from PIL import Image, ImageDraw, ImageFont

FONT = os.path.expanduser('~/Library/Fonts/IBMPlexSans-Bold.ttf')
CHARS = " !'+,-./0123456789:?ABCDEFGHIJKLMNOPQRSTUVWXYZ"
GAP = 2                                          # blank columns after each glyph


def level(a):
    return 0 if a < 40 else 1 if a < 110 else 2 if a < 190 else 3


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('out_h')
    ap.add_argument('--size', type=int, default=30)
    ap.add_argument('--preview')
    args = ap.parse_args()

    font = ImageFont.truetype(FONT, args.size)
    asc, desc = font.getmetrics()
    top = min(font.getbbox(c)[1] for c in CHARS if c != ' ')
    bot = max(font.getbbox(c)[3] for c in CHARS if c != ' ')
    h = bot - top
    col_bytes = (h + 3) // 4

    glyphs = []                                  # (char, columns of levels)
    for c in CHARS:
        w = max(1, int(round(font.getlength(c))))
        img = Image.new('L', (w + 4, h), 0)
        ImageDraw.Draw(img).text((0, -top), c, font=font, fill=255)
        bb = img.getbbox()
        if c == ' ' or bb is None:
            cols = [[0] * h for _ in range(args.size // 3)]
        else:
            cols = [[level(img.getpixel((x, y))) for y in range(h)] for x in range(bb[0], bb[2])]
        cols += [[0] * h for _ in range(GAP)]
        glyphs.append((c, cols))

    out = ['/* Generated by tools/font2c.py (IBM Plex Sans Bold, SIL OFL 1.1): do not edit. */',
           '#ifndef FONT_DATA_H', '#define FONT_DATA_H', '', '#include <stdint.h>', '',
           '#define FONT_H          %du' % h,
           '#define FONT_COL_BYTES  %du' % col_bytes,
           '#define FONT_CHARS      "%s"' % CHARS.replace('\\', '\\\\').replace('"', '\\"'), '',
           '/* Glyph i (FONT_CHARS[i]): columns [font_start[i], font_start[i+1]) of font_cols */',
           '#ifdef FONT_DATA_TABLES']
    starts, n = [], 0
    for _, cols in glyphs:
        starts.append(n)
        n += len(cols)
    starts.append(n)
    out.append('static const uint16_t font_start[%d] = {' % len(starts))
    for k in range(0, len(starts), 12):
        out.append('    ' + ', '.join(str(v) for v in starts[k:k + 12]) + ',')
    out.append('};')
    data = []
    for _, cols in glyphs:
        for col in cols:
            for b in range(col_bytes):
                v = 0
                for k in range(4):
                    y = 4 * b + k
                    if y < h:
                        v |= col[y] << (2 * k)
                data.append(v)
    out.append('static const uint8_t  font_cols[%d] = {' % len(data))
    for k in range(0, len(data), 16):
        out.append('    ' + ', '.join('0x%02x' % v for v in data[k:k + 16]) + ',')
    out += ['};', '#endif /* FONT_DATA_TABLES */', '', '#endif /* FONT_DATA_H */', '']
    open(args.out_h, 'w').write('\n'.join(out))

    if args.preview:
        text = 'ARVERN + BELENOS: 0123456789 !?'
        idx = [CHARS.index(c) for c in text]
        cols = [col for i in idx for col in glyphs[i][1]]
        img = Image.new('L', (len(cols), h))
        img.putdata([85 * cols[x][y] for y in range(h) for x in range(len(cols))])
        img.resize((img.width * 3, h * 3), Image.NEAREST).save(args.preview)
    print('font %d px high, %d glyphs, %d columns, %d bytes' % (h, len(glyphs), n, len(data) + 2 * len(starts)))


if __name__ == '__main__':
    main()
