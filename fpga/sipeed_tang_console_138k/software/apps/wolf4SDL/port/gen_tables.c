/* Host generator: the constant tables of the target build, computed with the
 * original Wolf4SDL formulas (BuildTables, CalcProjection), plus checks of the
 * table-driven versions against those formulas */
#include <math.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>

#define PI          3.141592657
#define GLOBAL1     (1l<<16)
#define ANGLES      360
#define ANGLEQUAD   (ANGLES/4)
#define FINEANGLES  3600
#define MINDIST     0x5800l
#define FOCALLENGTH (0x5700l)
#define VIEWGLOBAL  0x10000

int wolf_atan2_deg(int32_t dy, int32_t dx);
static const float radtoint = (float)(FINEANGLES/2/PI);

static int orig_pixelangle(int i, int viewwidth)
{
    double facedist = FOCALLENGTH + MINDIST;
    double tang = (int32_t)i*VIEWGLOBAL/viewwidth/facedist;
    float angle = (float) atan(tang);
    return (int) (angle*radtoint);
}

static int orig_atan2(int32_t deltay, int32_t deltax)
{
    float angle = (float) atan2 ((float) deltay, (float) deltax);
    if (angle<0) angle = (float) (M_PI*2+angle);
    return (int) (angle/(M_PI*2)*ANGLES);
}

int main(int argc, char **argv)
{
    int32_t finetangent[FINEANGLES/4];
    int32_t sintable[ANGLES+ANGLES/4];
    int i, k;

    for (i = 0; i < FINEANGLES/8; i++) {
        double tang = tan((i+0.5)/radtoint);
        finetangent[i] = (int32_t)(tang*GLOBAL1);
        finetangent[FINEANGLES/4-1-i] = (int32_t)((1/tang)*GLOBAL1);
    }
    float angle = 0, anglestep = (float)(PI/2/ANGLEQUAD);
    for (i = 0; i < ANGLEQUAD; i++) {
        int32_t value = (int32_t)(GLOBAL1*sin(angle));
        sintable[i] = sintable[i+ANGLES] = sintable[ANGLES/2-i] = value;
        sintable[ANGLES-i] = sintable[ANGLES/2+i] = -value;
        angle += anglestep;
    }
    sintable[ANGLEQUAD] = 65536;
    sintable[3*ANGLEQUAD] = -65536;

    if (argc > 1 && argv[1][0] == 't') {           /* tan_q24.inc */
        for (k = 1; k <= 89; k++) printf("%10uu,%s", (uint32_t) llround(tan(k*M_PI/180)*16777216.0), (k % 6) ? " " : "\n");
        printf("\n");
        return 0;
    }
    if (argc > 1 && argv[1][0] == 'c') {           /* checks */
        int bad = 0, n = 0;
        /* pixelangle: breakpoint table vs the formula, every view width */
        int maxang = orig_pixelangle(159, 320) + 2, bp[512], vw;
        for (k = 0, i = 0; k <= maxang; k++) { while (i < 32768 && orig_pixelangle(1, 1) * 0 + (int)((float) atan((double) i / (FOCALLENGTH + MINDIST)) * radtoint) < k) i++; bp[k] = i; }
        for (vw = 16; vw <= 320; vw += 16)
            for (i = 0; i < vw / 2; i++) {
                int t = (int32_t) i*VIEWGLOBAL/vw, a = 0;
                while (a + 1 <= maxang && bp[a + 1] <= t) a++;
                n++; if (a != orig_pixelangle(i, vw)) bad++;
            }
        printf("pixelangle: %d mismatches in %d\n", bad, n);
        /* atan2: grid of tile distances with sub-tile offsets */
        long mis = 0, tot = 0; srand(1);
        for (int dy = -70; dy <= 70; dy++)
            for (int dx = -70; dx <= 70; dx++)
                for (int r = 0; r < 20; r++) {
                    int32_t y = dy * 65536 + (r ? rand() % 65536 : 0), x = dx * 65536 + (r ? rand() % 65536 : 0);
                    tot++; if (wolf_atan2_deg(y, x) != orig_atan2(y, x)) mis++;
                }
        printf("atan2: %ld mismatches in %ld\n", mis, tot);
        return 0;
    }
    /* wolf_tables.c */
    printf("/* Generated by port/gen_tables.c from the Wolf4SDL formulas: do not edit */\n");
    printf("#include \"wl_def.h\"\n\nconst int32_t finetangent[FINEANGLES/4] = {");
    for (i = 0; i < FINEANGLES/4; i++) printf("%s%d,", (i % 8) ? " " : "\n    ", finetangent[i]);
    printf("\n};\n\nconst fixed sintable[ANGLES+ANGLES/4] = {");
    for (i = 0; i < ANGLES+ANGLES/4; i++) printf("%s%d,", (i % 8) ? " " : "\n    ", sintable[i]);
    printf("\n};\n\nconst fixed *costable = sintable+(ANGLES/4);\n\n");
    {
        int maxang = orig_pixelangle(159, 320) + 2;
        printf("/* pixelangle_bp[k]: the smallest i * VIEWGLOBAL / viewwidth whose ray angle is >= k fine angles */\n");
        printf("const uint16_t pixelangle_bp[%d] = {", maxang + 1);
        for (k = 0, i = 0; k <= maxang; k++) {
            while (i < 32768 && (int)((float) atan((double) i / (FOCALLENGTH + MINDIST)) * radtoint) < k) i++;
            printf("%s%d,", (k % 10) ? " " : "\n    ", i);
        }
        printf("\n};\nconst int pixelangle_bp_n = %d;\n", maxang + 1);
    }
    return 0;
}
