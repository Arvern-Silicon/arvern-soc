# Renders the fonts and the title of the text demo from IBM Plex Sans (SIL
# Open Font License) in the layout Belenos EXEC_EXPAND reads: every glyph a
# packed rectangle of fixed cell size (source pitch 0 = the cell width), row by
# row, pixels LSB first at 1, 2 or 4 bits per pixel, glyph after glyph.
#
#   mono : 1 bpp, 8 x 16 cells, printable ASCII        (console)
#   sans : 2 bpp, 10 x 20 cells, printable ASCII       (antialiased body text)
#   big  : 4 bpp, 22 x 32 cells, capitals and digits   (headlines, 15-step gradient)
#   title: 2 bpp, one 256 x 40 image                   (zoomed and rotated)
#
#   tools/text2c.py <out.h> [--preview DIR]
#----------------------------------------------------------------------------
import argparse
import os
from PIL import Image, ImageDraw, ImageFont

FONT_DIR = os.path.expanduser('~/Library/Fonts')
ASCII    = ''.join(chr(c) for c in range(32, 127))
BIG      = " !-.0123456789:?ABCDEFGHIJKLMNOPQRSTUVWXYZ"
TITLE    = "aRVern + Belenos"


def render(face, size, ch, cell_w, cell_h, baseline):
    """One glyph, antialiased (0..255), centred in a cell_w x cell_h cell;
    squeezed horizontally when it is wider than the cell."""
    font = ImageFont.truetype(os.path.join(FONT_DIR, face), size)
    w = max(1, int(round(font.getlength(ch)))) + 2
    img = Image.new('L', (w, cell_h), 0)
    ImageDraw.Draw(img).text((1, baseline), ch, font=font, fill=255)
    bb = img.getbbox()
    cell = Image.new('L', (cell_w, cell_h), 0)
    if bb is None:
        return cell
    glyph = img.crop((bb[0], 0, bb[2], cell_h))
    if glyph.width > cell_w - 1:
        glyph = glyph.resize((cell_w - 1, cell_h), Image.LANCZOS)
    cell.paste(glyph, ((cell_w - glyph.width) // 2, 0))
    return cell


def levels(img, bpp):
    """Pixels to source values: 1 bpp ink, 2 bpp coverage 0..3, 4 bpp ink with a
    vertical gradient 1..15."""
    out = []
    for y in range(img.height):
        for x in range(img.width):
            a = img.getpixel((x, y))
            if bpp == 1:
                out.append(1 if a >= 110 else 0)
            elif bpp == 2:
                out.append(0 if a < 40 else 1 if a < 110 else 2 if a < 190 else 3)
            else:
                out.append(0 if a < 100 else 1 + (14 * y) // (img.height - 1))
    return out


def pack(values, bpp):
    """Source pixel p at bits [p*bpp, p*bpp + bpp) of the byte stream, LSB first."""
    data = bytearray((len(values) * bpp + 7) // 8)
    for p, v in enumerate(values):
        bit = p * bpp
        data[bit // 8] |= v << (bit % 8)
    return data


def c_array(name, data):
    out = ['static const uint8_t %s[%d] __attribute__((aligned(4))) = {' % (name, len(data))]
    for k in range(0, len(data), 16):
        out.append('    ' + ', '.join('0x%02x' % v for v in data[k:k + 16]) + ',')
    out.append('};')
    return out


def font(face, size, chars, cell_w, cell_h, baseline, bpp):
    cells = [render(face, size, c, cell_w, cell_h, baseline) for c in chars]
    vals = []
    for c in cells:
        vals += levels(c, bpp)
    return cells, pack(vals, bpp)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('out_h')
    ap.add_argument('--preview')
    args = ap.parse_args()

    mono_cells, mono = font('IBMPlexSans-Medium.ttf',   13, ASCII, 8, 16, -1, 1)
    sans_cells, sans = font('IBMPlexSans-SemiBold.ttf', 16, ASCII, 10, 20, -1, 2)
    big_cells,  big  = font('IBMPlexSans-Bold.ttf',     31, BIG, 22, 32, -5, 4)

    tfont = ImageFont.truetype(os.path.join(FONT_DIR, 'IBMPlexSans-Bold.ttf'), 29)
    timg = Image.new('L', (256, 40), 0)
    tw = tfont.getlength(TITLE)
    ImageDraw.Draw(timg).text(((256 - tw) / 2, -4), TITLE, font=tfont, fill=255)
    title = pack(levels(timg, 2), 2)

    out = ['/* Generated by tools/text2c.py (IBM Plex Sans, SIL OFL 1.1): do not edit. */',
           '#ifndef TEXT_DATA_H', '#define TEXT_DATA_H', '', '#include <stdint.h>', '',
           '/* Fonts for EXEC_EXPAND: glyph i of a font is the i-th packed cell (pitch 0);',
           '   word-aligned, so a cell of whole words can also be pushed as immediate data */',
           '#define MONO_W          8u   /* 1 bpp, ASCII 32..126 */',
           '#define MONO_H          16u',
           '#define SANS_W          10u  /* 2 bpp, ASCII 32..126 */',
           '#define SANS_H          20u',
           '#define BIG_W           22u  /* 4 bpp, BIG_CHARS, values 1..15 top to bottom */',
           '#define BIG_H           32u',
           '#define BIG_CHARS       "%s"' % BIG,
           '#define TITLE_W         256u /* 2 bpp */',
           '#define TITLE_H         40u',
           '', '#ifdef TEXT_DATA_TABLES']
    out += c_array('mono_bits', mono)
    out += c_array('sans_bits', sans)
    out += c_array('big_bits', big)
    out += c_array('title_bits', title)
    out += ['#endif /* TEXT_DATA_TABLES */', '', '#endif /* TEXT_DATA_H */', '']
    open(args.out_h, 'w').write('\n'.join(out))
    print('mono %d B, sans %d B, big %d B, title %d B, total %d B' %
          (len(mono), len(sans), len(big), len(title), len(mono) + len(sans) + len(big) + len(title)))

    if args.preview:
        os.makedirs(args.preview, exist_ok=True)
        for name, cells, text in (('mono', mono_cells, 'aRVern RISC-V core: console 0123'),
                                  ('sans', sans_cells, 'Antialiased text, 2 bits per pixel!'),
                                  ('big', big_cells, 'BELENOS GPU 2026')):
            chars = ASCII if name != 'big' else BIG
            w, h = cells[0].size
            img = Image.new('L', (w * len(text), h))
            for i, c in enumerate(text):
                img.paste(cells[chars.index(c)], (i * w, 0))
            img.resize((img.width * 3, h * 3), Image.NEAREST).save(os.path.join(args.preview, name + '.png'))
        timg.resize((256 * 3, 120), Image.NEAREST).save(os.path.join(args.preview, 'title.png'))


if __name__ == '__main__':
    main()
