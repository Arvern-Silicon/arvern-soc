# Omnispeak's script variables (EPISODE.CK4 and the files it includes: the
# integers, strings, arrays and the 370 actions) as C, so that the Tang build
# links them instead of reading and parsing the scripts at start-up: no
# variable tables, no arena, and every CK_INT / CK_ACTION / ... a constant.
#
#   tools/gen_vars.py DUMP SRC_DIR OUT_DIR    -> OUT_DIR/keen4_vars.h, .c
#
# DUMP is what the engine prints with ARV_DUMP_VARS and CK_VAR_TYPECHECK
# (CK_VAR_Dump, ck_act.c: the parser's own result, after the scripts are
# read); SRC_DIR the engine's sources, scanned for the names they use: a name
# the scripts do not define gets the default the code gives (CK_INT's
# second argument, CK_FILENAME's file name, CK_STRING's name, 0, NULL).
#----------------------------------------------------------------------------
import os, re, sys


def cstr(b):
    out = '"'
    for c in b:
        if c in (0x22, 0x5C):
            out += '\\' + chr(c)
        elif 0x20 <= c < 0x7F:
            out += chr(c)
        else:
            out += '\\%03o' % c
    return out + '"'


def unhex(h):
    return b'' if h == '.' else bytes.fromhex(h)


def uses(src):
    """(macro, name, default) for every variable macro in the engine"""
    found = []
    for f in sorted(os.listdir(src)):
        if not f.endswith(('.c', '.h')) or f == 'ck_act.h':
            continue
        t = open(os.path.join(src, f), encoding='latin1').read()
        for m in re.finditer(r'\b(CK_INT|CK_CHUNKNUM|CK_SOUNDNUM|CK_ACTION|CK_FUNCTION|CK_CHUNKID|CK_INTARRAY|'
                             r'CK_INTELEMENT|CK_STRINGARRAY|CK_STRINGELEMENT|CK_FILENAME|CK_STRING)\s*\(\s*(\w+)', t):
            macro, name = m.group(1), m.group(2)
            default = None
            if macro in ('CK_INT', 'CK_FILENAME'):
                i, depth = m.end(), 0
                while t[i] != ',':
                    i += 1
                j = i + 1
                while depth or t[j] != ')':
                    depth += {'(': 1, ')': -1}.get(t[j], 0)
                    j += 1
                default = t[i + 1:j].strip()
            found.append((macro, name, default))
    return found


def main():
    dump, src, out = sys.argv[1:4]
    ints, strs, iarr, sarr, acts, actions = {}, {}, {}, {}, {}, []
    for line in open(dump, encoding='latin1'):
        p = line.split()
        if not p:
            continue
        if p[0] == 'V' and p[1] == 'INT':
            ints[p[2]] = int(p[3])
        elif p[0] == 'V' and p[1] == 'STR':
            strs[p[2]] = unhex(p[3]) if len(p) > 3 else b''
        elif p[0] == 'V' and p[1] == 'IARR':
            iarr[p[2]] = [int(x) for x in p[4:4 + int(p[3])]]
        elif p[0] == 'V' and p[1] == 'SARR':
            sarr[p[2]] = [unhex(x) for x in p[4:4 + int(p[3])]]
        elif p[0] == 'V' and p[1] == 'ACT':
            acts[p[2]] = int(p[3])
        elif p[0] == 'A':
            actions.append(p[1:])
    funcs = {}
    for f in os.listdir(os.path.join(src, '..', 'data', 'keen4')):
        for line in open(os.path.join(src, '..', 'data', 'keen4', f), encoding='latin1'):
            m = re.match(r'\s*%function\s+(\w+)\s+(\w+)', line)
            if m:
                funcs[m.group(1)] = m.group(2)

    h = ['/* Generated by tools/gen_vars.py from Omnispeak\'s Keen 4 scripts: do not edit */',
         '#ifndef KEEN4_VARS_H', '#define KEEN4_VARS_H', '#include <stdint.h>', '',
         # ck_actions[] (the type is complete in ck_def.h, which declares it)
         '#define CK_NUM_ACTIONS %d' % len(actions),
         'extern const intptr_t ck_varZeros[96];', 'extern const char *const ck_varEmpty[96];', '']
    for n in sorted(ints):
        h.append('#define INT_%s (%d)' % (n, ints[n]))
    for n in sorted(acts):
        h.append('#define ACT_%s ((CK_action *)&ck_actions[%d])' % (n, acts[n]))
    for n in sorted(strs):
        h.append('#define STRING_%s %s' % (n, cstr(strs[n])))
        h.append('#define FILENAME_%s %s' % (n, cstr(strs[n])))
    for n in sorted(iarr):
        h.append('extern const intptr_t INTARRAY_%s[%d];' % (n, len(iarr[n])))
    for n in sorted(sarr):
        h.append('extern const char *const STRARRAY_%s[%d];' % (n, len(sarr[n])))
    for n in sorted(funcs):
        h.append('void %s();' % funcs[n])
        h.append('#define FUNC_%s (&%s)' % (n, funcs[n]))
    h.append('')
    h.append('/* Names the scripts leave out: the code\'s defaults */')
    done = set()
    for macro, name, default in uses(src):
        key = (macro, name)
        if key in done:
            continue
        done.add(key)
        if macro in ('CK_INT', 'CK_CHUNKNUM', 'CK_SOUNDNUM', 'CK_CHUNKID') and name not in ints:
            h.append('#ifndef INT_%s\n#define INT_%s (%s)\n#endif' % (name, name, default if macro == 'CK_INT' else '0'))
        elif macro == 'CK_ACTION' and name not in acts:
            h.append('#ifndef ACT_%s\n#define ACT_%s ((CK_action *)0)\n#endif' % (name, name))
        elif macro == 'CK_STRING' and name not in strs:
            h.append('#ifndef STRING_%s\n#define STRING_%s "%s"\n#endif' % (name, name, name))
        elif macro == 'CK_FILENAME' and name not in strs:
            h.append('#ifndef FILENAME_%s\n#define FILENAME_%s FS_AdjustExtension(%s)\n#endif' % (name, name, default))
        elif macro in ('CK_INTARRAY', 'CK_INTELEMENT') and name not in iarr:
            h.append('#ifndef INTARRAY_%s\n#define INTARRAY_%s ck_varZeros\n#endif' % (name, name))
        elif macro in ('CK_STRINGARRAY', 'CK_STRINGELEMENT') and name not in sarr:
            h.append('#ifndef STRARRAY_%s\n#define STRARRAY_%s ck_varEmpty\n#endif' % (name, name))
        elif macro == 'CK_FUNCTION' and name not in funcs:
            h.append('#ifndef FUNC_%s\n#define FUNC_%s 0\n#endif' % (name, name))
    h += ['', '#endif', '']
    open(os.path.join(out, 'keen4_vars.h'), 'w').write('\n'.join(h))

    fnames = sorted({a[i] for a in actions for i in (10, 11, 12)} - {'NULL'})
    if '?' in fnames:
        sys.exit('gen_vars: an action calls a function the engine does not register')
    c = ['/* Generated by tools/gen_vars.py from Omnispeak\'s Keen 4 scripts: do not edit */',
         '#include "ck_def.h"', '#include "keen4_vars.h"', '',
         '/* the actions\' functions (their parameters differ: unprototyped) */']
    c += ['void %s();' % f for f in fnames]
    c += ['', 'const intptr_t ck_varZeros[96];', 'const char *const ck_varEmpty[96] = { "" };', '']
    for n in sorted(iarr):
        c.append('const intptr_t INTARRAY_%s[%d] = { %s };' % (n, len(iarr[n]), ', '.join(map(str, iarr[n]))))
    for n in sorted(sarr):
        c.append('const char *const STRARRAY_%s[%d] = {\n\t%s\n};' % (n, len(sarr[n]), ',\n\t'.join(cstr(s) for s in sarr[n])))
    c += ['', '/* chunkLeft, chunkRight, type, protectAnimation, stickToGround, timer, velX, velY,',
          '   think, collide, draw, next, compatDosPointer */',
          'const CK_action ck_actions[%d] = {' % len(actions)]
    for a in actions:
        idx, dos, cl, cr, typ, prot, stick, timer, vx, vy, th, co, dr, nx = a
        fn = lambda s: 'NULL' if s == 'NULL' else s
        nxt = 'NULL' if nx == '-1' else '(CK_action *)&ck_actions[%s]' % nx
        c.append('\t{ %s, %s, (CK_ActionType)%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s },' %
                 (cl, cr, typ, prot, stick, timer, vx, vy, fn(th), fn(co), fn(dr), nxt, dos))
    c += ['};', '']
    open(os.path.join(out, 'keen4_vars.c'), 'w').write('\n'.join(c))
    print('keen4_vars: %d ints, %d strings, %d arrays, %d string arrays, %d actions' %
          (len(ints), len(strs), len(iarr), len(sarr), len(actions)))


if __name__ == '__main__':
    main()
